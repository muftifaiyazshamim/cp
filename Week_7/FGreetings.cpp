#include <bits/stdc++.h>
using namespace std;

int main() {
    
    int t;cin>>t;
    while (t--)
    {
        int a;cin>>a;
        vector<pair<int,int>>v;
        for (int i = 0; i < a; i++)
        {
            int x,y;cin>>x>>y;
            v.push_back({x,y});
        }
        
    }
    

    return 0;
}